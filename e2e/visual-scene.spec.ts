  await page.goto('/?obra=bienvenida');
  await expect(page.getByTestId('writing-canvas')).toBeVisible();
  await page.getByTestId('open-works').click();
  await page.getByTestId('new-work-title').fill('La llave del cuadro');
  await page.getByTestId('mode-taller').check();
  await page.getByTestId('create-work').click();
  await expect(page.getByTestId('work-title')).toHaveValue('La llave del cuadro');
  await page.getByTestId('prose').fill('Busqué con mi linterna hasta encontrar la llave bajo el cuadro.');
  await page.getByTestId('open-visual-scene').click();
  const dialog = page.getByTestId('visual-scene-dialog');
  await page.getByTestId('visual-mode').selectOption('room');
  await page.getByTestId('visual-description').fill('Una cocina antigua, sin la llave.');
  await page.getByTestId('visual-style').selectOption('comic');
