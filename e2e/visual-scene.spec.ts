  await expect(page.getByTestId('visual-x')).toHaveValue('73');
  await page.getByTestId('visual-x').fill('72'); await page.getByTestId('visual-y').fill('64');
  await page.screenshot({ path: testInfo.outputPath('composicion-escritorio.png') });
  await page.getByTestId('visual-test-toggle').click();
  const testRoom = dialog.getByTestId('room-search');
  await testRoom.focus();
